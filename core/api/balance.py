def _clean_round(val, mult):
    """按数值量级做整洁取整（1/5/10/50/100/500），避免出现零碎怪数"""
    raw = max(1.0, float(val) * float(mult))
    if raw < 20:
        return int(round(raw))
    if raw < 100:
        return max(5, int(round(raw / 5.0) * 5))
    if raw < 1000:
        return max(10, int(round(raw / 10.0) * 10))
    if raw < 10000:
        return max(50, int(round(raw / 50.0) * 50))
    if raw < 100000:
        return max(100, int(round(raw / 100.0) * 100))
    return max(500, int(round(raw / 500.0) * 500))


